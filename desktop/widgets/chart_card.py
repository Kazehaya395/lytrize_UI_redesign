"""desktop/widgets/chart_card.py -- Per-chart card widget for the analysis page.

Replaces the Streamlit ``modules/ui/chart_card.py`` with a native Qt widget
that shows a chart, its title, notes, and action buttons (edit, delete, move).
"""

from __future__ import annotations

import logging
from typing import Any, Optional

from PySide6.QtCore import Qt, Signal, QPoint, QTimer
from PySide6.QtWidgets import (
    QWidget, QVBoxLayout, QHBoxLayout, QGridLayout, QLabel, QPushButton,
    QTextEdit, QFrame, QSizePolicy, QDialog, QDialogButtonBox,
)


log = logging.getLogger(__name__)

# id -> friendly display name, from the same list the analysis-type picker
# uses, so a card header reads "Type: Statistical" instead of the raw id.
_TYPE_NAME = {
    "descriptive": "Descriptive",
    "statistical": "Statistical",
    "distribution": "Distribution",
    "correlation": "Correlation",
    "categorical": "Categorical Bar",
    "pie_chart": "Pie & Donut",
    "time_series": "Time Series",
    "scatter_plot": "Scatter Plot",
    "matrix_heatmap": "Matrix Heatmap",
    "matrix_table": "Pivot Table",
    "map_plot": "Map Plot",
}


def _style_legacy_figure(fig, style, chart_type):
    """Legacy no-op; renderer styling is stored on the ChartModel."""
    return fig


# Glyphs for the resize handles. The two plain edges are NOT left blank: an
# empty QLabel renders as nothing at all, so a border-only handle on a busy
# chart is effectively invisible (which is how the original corner-only handle
# came to be reported as "no resize handler"). These are geometric marks that
# point along the axis each edge controls.
_RESIZE_GLYPHS = {"right": "\u2502", "bottom": "\u2500", "corner": "\u25e2"}


class ChartCard(QFrame):
    """A single chart card with title, plot, notes, and actions."""

    delete_requested = Signal(str)      # uid
    edit_requested = Signal(str)        # uid
    slicer_requested = Signal(str)      # uid -- add a slicer scoped to this chart
    move_up_requested = Signal(str)     # uid
    move_down_requested = Signal(str)   # uid
    note_changed = Signal(str, str)     # uid, note_text
    style_changed = Signal(str, dict)   # uid, style dict -- persisted by the page, same
                                         # pattern as note_changed, so a style edit survives
                                         # a session save instead of only living on the
                                         # in-memory ChartCard instance
    fullwidth_toggled = Signal(str, bool)  # uid, is_full_width -- dashboard grid only

    # -- Dashboard tiling ---------------------------------------------------
    # Emitted with the GLOBAL cursor position when a drag/resize gesture
    # starts on the card's grip or resize handle. The owning canvas tracks the
    # rest of the gesture (it knows the grid geometry; the card does not) and
    # moves the card itself, so the card never needs to know about columns.
    drag_started = Signal(str, QPoint)              # uid, global_pos
    resize_started = Signal(str, QPoint, str)    # uid, global_pos, edge
                                                 # edge: "right" | "bottom" |
                                                 # "corner" -- which span the
                                                 # gesture is allowed to change

    def __init__(self, uid: str, title: str, fig: Any = None, chart_type: str = "",
                 meta: Optional[dict] = None, parent=None,
                 chart_model: Optional[dict] = None) -> None:
        super().__init__(parent)
        self.uid = uid
        self._title = title
        self._fig = fig
        self._chart_model = chart_model
        self._legacy_source_fig = (
            None if (chart_model or {}).get("source", {}).get("engine") == "polars"
            else fig)
        # The figure exactly as generated by the analysis run, before any
        # styling is applied. Every style change re-derives from this,
        # never from self._fig (which may already be styled) -- same
        # "always start clean" approach as apply_chart_style() itself, so
        # toggling a control on/off can't compound with earlier toggles.
        self._base_fig = fig
        self._chart_type = chart_type
        self._meta = meta or {}
        self._style = dict(self._meta.get("display_options", {}))
        if self._chart_model is None and isinstance(fig, dict):
            try:
                from modules.legacy_plotly_adapter import figure_to_chart_model
                self._chart_model = figure_to_chart_model(
                    fig, uid=uid, chart_type=chart_type, title=title, meta=self._meta)
            except Exception:
                pass
        if self._chart_model is None:
            from modules.chart_model import make_chart_model
            self._chart_model = make_chart_model(
                uid=uid or "unavailable", chart_type="categorical", title=title,
                data={"dimensions": [], "series": []},
                display={"empty_message": "This saved chart format is unsupported",
                         "legend": {"show": False}},
                source={"engine": "legacy_import"})
        self._fig = None
        self._base_fig = None
        # Style ticks (slider drags) stream in as a flood, and each apply is
        # a full Plotly re-push. Coalesce them: the LAST style wins ~150ms
        # after the user pauses, instead of stalling the UI per tick.
        self._style_debounce = QTimer(self)
        self._style_debounce.setSingleShot(True)
        self._style_debounce.setInterval(150)
        self._style_debounce.timeout.connect(self._flush_style)
        self._pending_style = None

        self.setObjectName("chart_card")
        # No title label on the card, so the full (often long, elided in
        # the tab) chart title lives on the tile's tooltip.
        self.setToolTip(title)

        self._build_ui()

    # -- UI construction ----------------------------------------------------

    def _build_ui(self) -> None:
        # A QGridLayout whose first cell holds BOTH the plot and the action
        # bar (see the end of this method). The bar used to be the first item
        # of a QVBoxLayout, so its 28px buttons + 6px spacing pushed the whole
        # canvas down and the chart header -- anchored to the very top of the
        # canvas -- started ~40px below the card's top edge. That dead band is
        # the "gap between header and top edge" in the report. Overlaying the
        # bar instead lets the plot fill the card; the Plotly modebar is
        # nudged down in CSS (PlotlyWebView._SHELL_TEMPLATE) so the two never
        # overlap.
        layout = QGridLayout(self)
        self._content_grid = layout
        layout.setContentsMargins(8, 0, 8, 8)
        layout.setSpacing(6)

        # -- Action row (right-aligned) --
        # No title label and no "Type: ..." subtitle here: on the Analysis
        # page the tab already names the chart ("Statistical 1") and the
        # Plotly canvas renders the configured chart title, so a third copy
        # above the plot was pure duplicated chrome eating chart height. The
        # full title is still exposed via self._title / tooltip() for the
        # tab bar and tooltips, so nothing is lost.
        header = QHBoxLayout()
        header.setSpacing(4)
        header.addStretch(1)

        self.btn_up = QPushButton("⬆")
        self.btn_up.setFixedSize(28, 28)
        self.btn_up.setToolTip("Move up")
        self.btn_up.setProperty("kind", "icon")
        self.btn_up.clicked.connect(lambda: self.move_up_requested.emit(self.uid))
        header.addWidget(self.btn_up)

        self.btn_down = QPushButton("⬇")
        self.btn_down.setFixedSize(28, 28)
        self.btn_down.setToolTip("Move down")
        self.btn_down.setProperty("kind", "icon")
        self.btn_down.clicked.connect(lambda: self.move_down_requested.emit(self.uid))
        header.addWidget(self.btn_down)

        self.btn_edit = QPushButton("✏️")
        self.btn_edit.setFixedSize(28, 28)
        self.btn_edit.setToolTip("Edit chart")
        self.btn_edit.setProperty("kind", "icon")
        self.btn_edit.clicked.connect(lambda: self.edit_requested.emit(self.uid))
        header.addWidget(self.btn_edit)

        # Per-chart slicer entry point: opens the same slicer form the
        # dashboard uses, born on "One chart" with this chart pre-picked.
        # Lives on the card because that is where the user is when they think
        # "filter THIS chart" -- the dashboard's left panel is a different page.
        self.btn_slicer = QPushButton("⊞")
        self.btn_slicer.setFixedSize(28, 28)
        self.btn_slicer.setToolTip("Add a slicer for this chart")
        self.btn_slicer.setProperty("kind", "icon")
        self.btn_slicer.clicked.connect(
            lambda: self.slicer_requested.emit(self.uid))
        header.addWidget(self.btn_slicer)

        self.btn_style = QPushButton("🎨")
        self.btn_style.setFixedSize(28, 28)
        self.btn_style.setToolTip("Chart style")
        self.btn_style.setProperty("kind", "icon")
        self.btn_style.clicked.connect(self._on_open_style_dialog)
        header.addWidget(self.btn_style)

        self.btn_delete = QPushButton("🗑")
        self.btn_delete.setFixedSize(28, 28)
        self.btn_delete.setToolTip("Delete chart")
        self.btn_delete.setProperty("kind", "icon")
        self.btn_delete.clicked.connect(lambda: self.delete_requested.emit(self.uid))
        header.addWidget(self.btn_delete)

        # Full-width toggle -- dashboard grid only (hidden by default, shown
        # on the Dashboard page). Lets one chart span the entire grid row.
        self.btn_fullwidth = QPushButton("⬌")
        self.btn_fullwidth.setFixedSize(28, 28)
        self.btn_fullwidth.setCheckable(True)
        self.btn_fullwidth.setToolTip("Full width row")
        self.btn_fullwidth.setProperty("kind", "icon")
        self.btn_fullwidth.setVisible(False)
        self.btn_fullwidth.toggled.connect(
            lambda checked: self.fullwidth_toggled.emit(self.uid, checked)
        )
        header.addWidget(self.btn_fullwidth)

        # All charts use the bundled, offline ECharts renderer.
        self.plot_view = self._make_model_view(self._chart_model)
        self.btn_style.setVisible(False)
        self.plot_view.set_chart_model(self._chart_model)
        # The plot owns grid cell (0,0); the action row is pinned into the SAME
        # cell, top-right, so it floats over the canvas instead of reserving a
        # row above it (which is what opened the gap under the header).
        bar = QWidget()
        hb = QHBoxLayout(bar)
        hb.setContentsMargins(0, 0, 0, 0)
        hb.setSpacing(4)
        # Drag grip on the LEFT of the action bar. Placed as a sibling rather
        # than by making the whole card draggable, because the card's whole
        # surface is a live Plotly canvas: dragging the chart itself would
        # fight panning/selecting, and a drag needs a deliberate grip.
        self.grip = QLabel("\u2838")
        self.grip.setFixedSize(24, 28)
        self.grip.setCursor(Qt.OpenHandCursor)
        self.grip.setToolTip("Drag to move \u00b7 drag a card edge to resize")
        self.grip.setAlignment(Qt.AlignCenter)
        # Object name so the theme can give the grip a visible plate. Without
        # one the braille glyph was painted straight onto the chart canvas at
        # the same weight as the plot's own text, which is why the affordance
        # read as missing entirely: there WAS a handle, but nothing on screen
        # said "this is draggable".
        self.grip.setObjectName("card_grip")
        hb.addWidget(self.grip)
        self._reparent_buttons(bar, hb)
        layout.addWidget(self.plot_view, 0, 0)
        layout.addWidget(bar, 0, 0, Qt.AlignTop | Qt.AlignRight)

        # -- Resize handles -------------------------------------------------
        # Edge handles plus the corner, rather than one corner dot. A single
        # corner meant a card could only be resized by dragging right AND down
        # at once, from the one spot where the scrollbar and the neighbouring
        # card's border compete for the same pixels. Separate edges give
        # independent horizontal and vertical control, which is what "adjust
        # the chart size" means on a grid dashboard.
        self.resize_handles: dict[str, QLabel] = {}
        edge_specs = (
            ("right", Qt.SizeHorCursor, Qt.AlignRight | Qt.AlignVCenter, 18),
            ("bottom", Qt.SizeVerCursor, Qt.AlignBottom | Qt.AlignHCenter, 18),
            ("corner", Qt.SizeFDiagCursor, Qt.AlignBottom | Qt.AlignRight, 22),
        )
        for name, cursor, alignment, size in edge_specs:
            handle = QLabel(_RESIZE_GLYPHS[name])
            handle.setObjectName(f"card_resize_{name}")
            handle.setFixedSize(size, size)
            handle.setCursor(cursor)
            handle.setToolTip(
                "Drag to resize" if name == "corner"
                else f"Drag the {name} edge to resize")
            handle.setAlignment(Qt.AlignCenter)
            layout.addWidget(handle, 0, 0, alignment)
            handle.mousePressEvent = self._make_resize_press(name)
            self.resize_handles[name] = handle
        # Back-compat alias: the corner is "the" resize handle, which is what
        # set_tiling_enabled() and the dashboard page already refer to.
        self.resize_handle = self.resize_handles["corner"]
        # Widgets sharing a grid cell are z-ordered by insertion; the bar is
        # added second so it is already in front, and raise_() makes that
        # explicit and survives later re-layouts of the plot.
        bar.raise_()
        self._action_bar = bar

        # -- Notes editor --
        self.notes = QTextEdit()
        self.notes.setObjectName("chart_notes")
        self.notes.setPlaceholderText("Add analysis notes…")
        self.notes.setMaximumHeight(80)
        # Styling lives in the global QSS (QTextEdit#chart_notes) so the
        # tile re-resolves its palette colours on every theme switch --
        # a widget-level sheet would freeze the build-time colours and
        # leave the notes unreadable after toggling to light mode.
        self.notes.textChanged.connect(self._on_notes_changed)
        layout.addWidget(self.notes, 1, 0)

        self.grip.mousePressEvent = self._on_grip_pressed
        self.grip.mouseReleaseEvent = self._on_grip_released

    def set_tiling_enabled(self, enabled: bool) -> None:
        """Show or hide the drag grip and every resize handle.

        The Analysis page shows one chart at a time in a tab strip, so there is
        nothing to tile there and the handles would just be decoration.
        """
        self.grip.setVisible(enabled)
        for handle in self.resize_handles.values():
            handle.setVisible(enabled)

    # -- Tiling gestures ---------------------------------------------------
    # These only REPORT that a gesture started (with the global cursor
    # position). The canvas owns the gesture: it knows the grid geometry, and
    # moving the card is its job, so the card stays a dumb tile.

    def _on_grip_pressed(self, event) -> None:
        self.grip.setCursor(Qt.ClosedHandCursor)
        self.drag_started.emit(self.uid, event.globalPosition().toPoint())

    def _on_grip_released(self, _event) -> None:
        self.grip.setCursor(Qt.OpenHandCursor)

    def _on_resize_pressed(self, event) -> None:
        self.resize_started.emit(self.uid, event.globalPosition().toPoint())

    def _make_resize_press(self, edge: str):
        """Build the press handler for one resize *edge*.

        Bound per handle so the EDGE is captured in the closure. The signal
        carries the edge as a third argument so the canvas can change only the
        span that was actually dragged -- dragging the right edge must not
        silently resize the card's height as well.
        """
        def handler(event) -> None:
            self.resize_started.emit(self.uid,
                                     event.globalPosition().toPoint(), edge)
        return handler

    def _reparent_buttons(self, bar: QWidget, hb: QHBoxLayout) -> None:
        """Move the action buttons into the floating overlay bar.

        Kept separate from _build_ui so the button definitions (and their
        order) stay in one readable block; this only relocates the widgets
        that were added to the old `header` layout.
        """
        for btn in (self.btn_fullwidth, self.btn_up, self.btn_down,
                    self.btn_edit, self.btn_slicer, self.btn_style,
                    self.btn_delete):
            # Re-adding a widget to another layout removes it from the first,
            # so the old `header` layout is left empty and collapses to 0.
            hb.addWidget(btn)

    # -- Public API ----------------------------------------------------------

    @staticmethod
    def _model_view_type(model: dict):
        if model.get("chart_type") == "data_table":
            from desktop.widgets.native_table_view import NativeTableView
            return NativeTableView
        from desktop.widgets.echarts_web_view import EChartsWebView
        return EChartsWebView

    @classmethod
    def _make_model_view(cls, model: dict):
        return cls._model_view_type(model)()

    def set_figure(self, fig: Any) -> None:
        """Update the card from a native model or historical figure JSON."""
        if isinstance(fig, dict) and fig.get("schema_version") == 1:
            self.set_chart_model(fig)
            return
        from modules.legacy_plotly_adapter import figure_to_chart_model
        model = figure_to_chart_model(fig, uid=self.uid,
                                      chart_type=self._chart_type,
                                      title=self._title, meta=self._meta)
        if model is not None:
            self.set_chart_model(model)

    def set_chart_model(self, model: dict, *, source_figure: Any = None) -> None:
        """Switch this card to a validated, renderer-neutral chart model."""
        from modules.chart_model import validate_chart_model

        normalized = validate_chart_model(model)
        old_view = getattr(self, "plot_view", None)
        expected_view = self._model_view_type(normalized)
        if old_view is None or not isinstance(old_view, expected_view):
            if old_view is not None:
                self._content_grid.removeWidget(old_view)
                old_view.deleteLater()
            self.plot_view = self._make_model_view(normalized)
            self._content_grid.addWidget(self.plot_view, 0, 0)
        self._chart_model = normalized
        self._fig = None
        self._base_fig = None
        if source_figure is not None:
            self._legacy_source_fig = source_figure
        self._title = normalized.get("title", self._title)
        self.setToolTip(self._title)
        self.btn_style.setVisible(False)
        self.plot_view.set_chart_model(normalized)

    def set_title(self, title: str) -> None:
        """Record the chart's title.

        There is no on-card title label any more (see _build_ui) -- the
        title is rendered by the Plotly canvas and shown in the tab label
        / tooltip. Keep it on the instance so the owning page can read it
        back and refresh the tab tooltip, and mirror it onto the card's
        own tooltip so hovering the tile still reveals the full title
        (it can be long and is elided in the tab).
        """
        self._title = title
        self.setToolTip(title)
        if self._chart_model is not None:
            self._chart_model["title"] = str(title)
            self.plot_view.set_chart_model(self._chart_model)

    def set_note(self, text: str) -> None:
        """Set the notes text without triggering the change signal."""
        self.notes.blockSignals(True)
        self.notes.setPlainText(text)
        self.notes.blockSignals(False)

    def note_text(self) -> str:
        """Return the current notes text."""
        return self.notes.toPlainText()

    def current_figure(self) -> Any:
        """Return the figure currently shown on this card (styled)."""
        return self._fig

    def refresh_view(self) -> None:
        """Re-push the current figure into the web view.

        Called when the card's tab becomes visible again: a
        ``QWebEngineView`` inside a hidden ``QTabWidget`` page does not
        reliably run its pending page load while off-screen, so a chart
        created while another tab was selected can stay blank until its
        figure is replayed after the tab is shown. ``Plotly.react`` is
        in-place, so replaying the already-computed figure is flicker-free.
        """
        try:
            if self._chart_model is not None and hasattr(self, "plot_view"):
                self.plot_view.set_chart_model(self._chart_model)
            elif self._fig is not None and hasattr(self, "plot_view"):
                self.plot_view.set_figure(self._fig)
        except Exception:
            log.debug("ChartCard.refresh_view failed", exc_info=True)

    def set_fullwidth(self, is_full_width: bool) -> None:
        """Set the full-width toggle state without re-emitting the signal
        (used to initialize a card from stored bridge state on refresh)."""
        self.btn_fullwidth.blockSignals(True)
        self.btn_fullwidth.setChecked(is_full_width)
        self.btn_fullwidth.blockSignals(False)

    def apply_style(self, style: dict) -> None:
        """Re-skin this card in place from a dashboard export-style dict.

        Only touches the card's own QSS (background/border/text color) --
        it never rebuilds the chart itself, so a color/typography tweak in
        the dashboard style panel stays instant instead of forcing a
        delete-and-recreate pass over every card on screen.
        """
        card_bg = style.get("ex_card", "#0f172a")
        border = style.get("ex_border", "#1e293b")
        self.setStyleSheet(
            f"QFrame#chart_card {{ background: {card_bg}; border: 1px solid {border};"
            f"  border-radius: 10px; }}"
        )
        # Text color used to be pushed onto the (now removed) title label.
        # The chart's own typography is themed through chart_display
        # (PlotlyWebView -> theme_figure) instead, so a dashboard export
        # re-skin only needs to move the card surface + border; forcing the
        # web view to re-theme is done via apply_theme().

    # -- Slots ---------------------------------------------------------------

    def _on_notes_changed(self) -> None:
        self.note_changed.emit(self.uid, self.notes.toPlainText())

    def _on_open_style_dialog(self) -> None:
        """Open the granular chart-style controls in a dialog. Changes
        apply live to this card's chart as the user adjusts controls
        (re-rendered via Plotly.react through set_figure, not a full
        page reload), and persist to self._meta on close so they're
        included the next time this chart is saved/exported."""
        dialog = QDialog(self)
        dialog.setWindowTitle(f"Style — {self._title}")
        dialog.setMinimumWidth(340)
        dlg_layout = QVBoxLayout(dialog)

        from desktop.widgets.chart_style_panel import ChartStylePanel
        panel = ChartStylePanel(chart_type=self._chart_type, style=self._style)
        panel.style_changed.connect(self._on_style_changed)
        dlg_layout.addWidget(panel)

        buttons = QDialogButtonBox(QDialogButtonBox.Close)
        buttons.rejected.connect(dialog.close)
        buttons.button(QDialogButtonBox.Close).clicked.connect(dialog.close)
        dlg_layout.addWidget(buttons)

        dialog.exec()

    def _on_style_changed(self, style: dict) -> None:
        """Queue a style change; the heavy re-push happens on pause.

        Slider drags emit a flood of ticks and each apply is a full Plotly
        re-render, which was the "chart style dialog freezes the app" report.
        The LAST style wins ~150ms after the user pauses. Tests that need a
        deterministic apply call flush_style() directly -- it is idempotent.
        """
        self._pending_style = dict(style)
        self._style_debounce.start()

    def flush_style(self) -> None:
        """Apply the queued style immediately (no-op when nothing queued)."""
        style = self._pending_style
        self._pending_style = None
        try:
            self._style_debounce.stop()
        except Exception:
            pass
        if style is None:
            return
        self._apply_style_now(style)

    def _flush_style(self) -> None:
        self.flush_style()

    def _apply_style_now(self, style: dict) -> None:
        """The former Plotly-only style dialog is retired."""
        return

    def current_meta(self) -> dict:
        """Return this card's metadata, including any style settings --
        callers persisting charts (session save, dashboard) should pull
        this instead of a stale meta dict captured before styling."""
        return dict(self._meta)
