"""desktop/widgets/chart_card.py -- Per-chart card widget for the analysis page.

Replaces the Streamlit ``modules/ui/chart_card.py`` with a native Qt widget
that shows a chart, its title, notes, and action buttons (edit, delete, move).
"""

from __future__ import annotations

import logging
from typing import Any, Optional

from PySide6.QtCore import Qt, Signal
from PySide6.QtWidgets import (
    QWidget, QVBoxLayout, QHBoxLayout, QGridLayout, QLabel, QPushButton,
    QTextEdit, QFrame, QSizePolicy, QDialog, QDialogButtonBox,
)

from desktop.widgets.plotly_web_view import PlotlyWebView
from desktop.widgets.chart_style_panel import ChartStylePanel
from chart_style import apply_chart_style
from services.analysis_service import ANALYSIS_OPTIONS

log = logging.getLogger(__name__)

# id -> friendly display name, from the same list the analysis-type picker
# uses, so a card header reads "Type: Statistical" instead of the raw id.
_TYPE_NAME = {opt["id"]: opt["name"] for opt in ANALYSIS_OPTIONS}


class ChartCard(QFrame):
    """A single chart card with title, plot, notes, and actions."""

    delete_requested = Signal(str)      # uid
    edit_requested = Signal(str)        # uid
    move_up_requested = Signal(str)     # uid
    move_down_requested = Signal(str)   # uid
    note_changed = Signal(str, str)     # uid, note_text
    style_changed = Signal(str, dict)   # uid, style dict -- persisted by the page, same
                                         # pattern as note_changed, so a style edit survives
                                         # a session save instead of only living on the
                                         # in-memory ChartCard instance
    fullwidth_toggled = Signal(str, bool)  # uid, is_full_width -- dashboard grid only

    def __init__(self, uid: str, title: str, fig: Any, chart_type: str = "",
                 meta: Optional[dict] = None, parent=None) -> None:
        super().__init__(parent)
        self.uid = uid
        self._title = title
        self._fig = fig
        # The figure exactly as generated by the analysis run, before any
        # styling is applied. Every style change re-derives from this,
        # never from self._fig (which may already be styled) -- same
        # "always start clean" approach as apply_chart_style() itself, so
        # toggling a control on/off can't compound with earlier toggles.
        self._base_fig = fig
        self._chart_type = chart_type
        self._meta = meta or {}
        self._style = dict(self._meta.get("display_options", {}))

        self.setObjectName("chart_card")
        # No title label on the card, so the full (often long, elided in
        # the tab) chart title lives on the tile's tooltip.
        self.setToolTip(title)

        self._build_ui()

    # -- UI construction ----------------------------------------------------

    def _build_ui(self) -> None:
        # A QGridLayout whose first cell holds BOTH the plot and the action
        # bar (see the end of this method). The bar used to be the first item
        # of a QVBoxLayout, so its 28px buttons + 6px spacing pushed the whole
        # canvas down and the chart header -- anchored to the very top of the
        # canvas -- started ~40px below the card's top edge. That dead band is
        # the "gap between header and top edge" in the report. Overlaying the
        # bar instead lets the plot fill the card; the Plotly modebar is
        # nudged down in CSS (PlotlyWebView._SHELL_TEMPLATE) so the two never
        # overlap.
        layout = QGridLayout(self)
        layout.setContentsMargins(8, 0, 8, 8)
        layout.setSpacing(6)

        # -- Action row (right-aligned) --
        # No title label and no "Type: ..." subtitle here: on the Analysis
        # page the tab already names the chart ("Statistical 1") and the
        # Plotly canvas renders the configured chart title, so a third copy
        # above the plot was pure duplicated chrome eating chart height. The
        # full title is still exposed via self._title / tooltip() for the
        # tab bar and tooltips, so nothing is lost.
        header = QHBoxLayout()
        header.setSpacing(4)
        header.addStretch(1)

        self.btn_up = QPushButton("⬆")
        self.btn_up.setFixedSize(28, 28)
        self.btn_up.setToolTip("Move up")
        self.btn_up.setProperty("kind", "icon")
        self.btn_up.clicked.connect(lambda: self.move_up_requested.emit(self.uid))
        header.addWidget(self.btn_up)

        self.btn_down = QPushButton("⬇")
        self.btn_down.setFixedSize(28, 28)
        self.btn_down.setToolTip("Move down")
        self.btn_down.setProperty("kind", "icon")
        self.btn_down.clicked.connect(lambda: self.move_down_requested.emit(self.uid))
        header.addWidget(self.btn_down)

        self.btn_edit = QPushButton("✏️")
        self.btn_edit.setFixedSize(28, 28)
        self.btn_edit.setToolTip("Edit chart")
        self.btn_edit.setProperty("kind", "icon")
        self.btn_edit.clicked.connect(lambda: self.edit_requested.emit(self.uid))
        header.addWidget(self.btn_edit)

        self.btn_style = QPushButton("🎨")
        self.btn_style.setFixedSize(28, 28)
        self.btn_style.setToolTip("Chart style")
        self.btn_style.setProperty("kind", "icon")
        self.btn_style.clicked.connect(self._on_open_style_dialog)
        header.addWidget(self.btn_style)

        self.btn_delete = QPushButton("🗑")
        self.btn_delete.setFixedSize(28, 28)
        self.btn_delete.setToolTip("Delete chart")
        self.btn_delete.setProperty("kind", "icon")
        self.btn_delete.clicked.connect(lambda: self.delete_requested.emit(self.uid))
        header.addWidget(self.btn_delete)

        # Full-width toggle -- dashboard grid only (hidden by default, shown
        # on the Dashboard page). Lets one chart span the entire grid row.
        self.btn_fullwidth = QPushButton("⬌")
        self.btn_fullwidth.setFixedSize(28, 28)
        self.btn_fullwidth.setCheckable(True)
        self.btn_fullwidth.setToolTip("Full width row")
        self.btn_fullwidth.setProperty("kind", "icon")
        self.btn_fullwidth.setVisible(False)
        self.btn_fullwidth.toggled.connect(
            lambda checked: self.fullwidth_toggled.emit(self.uid, checked)
        )
        header.addWidget(self.btn_fullwidth)

        # -- Plotly view --
        self.plot_view = PlotlyWebView()
        # No hard-coded floor — Expanding policy + parent layout stretch
        # means the chart auto-fits to whatever space the splitter leaves,
        # so there is never a scrollbar fighting the viewport.
        if self._style:
            self._fig = apply_chart_style(self._base_fig, self._style, self._chart_type)
        self.plot_view.set_figure(self._fig)
        # The plot owns grid cell (0,0); the action row is pinned into the SAME
        # cell, top-right, so it floats over the canvas instead of reserving a
        # row above it (which is what opened the gap under the header).
        bar = QWidget()
        hb = QHBoxLayout(bar)
        hb.setContentsMargins(0, 0, 0, 0)
        hb.setSpacing(4)
        self._reparent_buttons(bar, hb)
        layout.addWidget(self.plot_view, 0, 0)
        layout.addWidget(bar, 0, 0, Qt.AlignTop | Qt.AlignRight)
        # Widgets sharing a grid cell are z-ordered by insertion; the bar is
        # added second so it is already in front, and raise_() makes that
        # explicit and survives later re-layouts of the plot.
        bar.raise_()
        self._action_bar = bar

        # -- Notes editor --
        self.notes = QTextEdit()
        self.notes.setObjectName("chart_notes")
        self.notes.setPlaceholderText("Add analysis notes…")
        self.notes.setMaximumHeight(80)
        # Styling lives in the global QSS (QTextEdit#chart_notes) so the
        # tile re-resolves its palette colours on every theme switch --
        # a widget-level sheet would freeze the build-time colours and
        # leave the notes unreadable after toggling to light mode.
        self.notes.textChanged.connect(self._on_notes_changed)
        layout.addWidget(self.notes, 1, 0)

    def _reparent_buttons(self, bar: QWidget, hb: QHBoxLayout) -> None:
        """Move the action buttons into the floating overlay bar.

        Kept separate from _build_ui so the button definitions (and their
        order) stay in one readable block; this only relocates the widgets
        that were added to the old `header` layout.
        """
        for btn in (self.btn_fullwidth, self.btn_up, self.btn_down,
                    self.btn_edit, self.btn_style, self.btn_delete):
            # Re-adding a widget to another layout removes it from the first,
            # so the old `header` layout is left empty and collapses to 0.
            hb.addWidget(btn)

    # -- Public API ----------------------------------------------------------

    def set_figure(self, fig: Any) -> None:
        """Update the displayed figure with a freshly-generated (unstyled)
        figure -- e.g. after re-running the chart with different data or
        config. Re-applies any existing style on top of the new figure
        rather than dropping it, and updates _base_fig so later style
        changes derive from this new figure, not a stale one."""
        self._base_fig = fig
        self._fig = apply_chart_style(fig, self._style, self._chart_type) if self._style else fig
        if hasattr(self, 'plot_view'):
            self.plot_view.set_figure(self._fig)

    def set_title(self, title: str) -> None:
        """Record the chart's title.

        There is no on-card title label any more (see _build_ui) -- the
        title is rendered by the Plotly canvas and shown in the tab label
        / tooltip. Keep it on the instance so the owning page can read it
        back and refresh the tab tooltip, and mirror it onto the card's
        own tooltip so hovering the tile still reveals the full title
        (it can be long and is elided in the tab).
        """
        self._title = title
        self.setToolTip(title)

    def set_note(self, text: str) -> None:
        """Set the notes text without triggering the change signal."""
        self.notes.blockSignals(True)
        self.notes.setPlainText(text)
        self.notes.blockSignals(False)

    def note_text(self) -> str:
        """Return the current notes text."""
        return self.notes.toPlainText()

    def current_figure(self) -> Any:
        """Return the figure currently shown on this card (styled)."""
        return self._fig

    def refresh_view(self) -> None:
        """Re-push the current figure into the web view.

        Called when the card's tab becomes visible again: a
        ``QWebEngineView`` inside a hidden ``QTabWidget`` page does not
        reliably run its pending page load while off-screen, so a chart
        created while another tab was selected can stay blank until its
        figure is replayed after the tab is shown. ``Plotly.react`` is
        in-place, so replaying the already-computed figure is flicker-free.
        """
        try:
            if self._fig is not None and hasattr(self, "plot_view"):
                self.plot_view.set_figure(self._fig)
        except Exception:
            log.debug("ChartCard.refresh_view failed", exc_info=True)

    def current_figure(self) -> Any:
        """Return the figure currently shown on this card (styled)."""
        return self._fig

    def refresh_view(self) -> None:
        """Re-push the current figure into the web view.

        Called when the card's tab becomes visible again: a
        ``QWebEngineView`` inside a hidden ``QTabWidget`` page does not
        reliably run its pending page load while off-screen, so a chart
        created while another tab was selected can stay blank until its
        figure is replayed after the tab is shown. ``Plotly.react`` is
        in-place, so replaying the already-computed figure is flicker-free.
        """
        try:
            if self._fig is not None and hasattr(self, "plot_view"):
                self.plot_view.set_figure(self._fig)
        except Exception:
            log.debug("ChartCard.refresh_view failed", exc_info=True)

    def set_fullwidth(self, is_full_width: bool) -> None:
        """Set the full-width toggle state without re-emitting the signal
        (used to initialize a card from stored bridge state on refresh)."""
        self.btn_fullwidth.blockSignals(True)
        self.btn_fullwidth.setChecked(is_full_width)
        self.btn_fullwidth.blockSignals(False)

    def apply_style(self, style: dict) -> None:
        """Re-skin this card in place from a dashboard export-style dict.

        Only touches the card's own QSS (background/border/text color) --
        it never rebuilds the chart itself, so a color/typography tweak in
        the dashboard style panel stays instant instead of forcing a
        delete-and-recreate pass over every card on screen.
        """
        card_bg = style.get("ex_card", "#0f172a")
        border = style.get("ex_border", "#1e293b")
        self.setStyleSheet(
            f"QFrame#chart_card {{ background: {card_bg}; border: 1px solid {border};"
            f"  border-radius: 10px; }}"
        )
        # Text color used to be pushed onto the (now removed) title label.
        # The chart's own typography is themed through chart_display
        # (PlotlyWebView -> theme_figure) instead, so a dashboard export
        # re-skin only needs to move the card surface + border; forcing the
        # web view to re-theme is done via apply_theme().

    # -- Slots ---------------------------------------------------------------

    def _on_notes_changed(self) -> None:
        self.note_changed.emit(self.uid, self.notes.toPlainText())

    def _on_open_style_dialog(self) -> None:
        """Open the granular chart-style controls in a dialog. Changes
        apply live to this card's chart as the user adjusts controls
        (re-rendered via Plotly.react through set_figure, not a full
        page reload), and persist to self._meta on close so they're
        included the next time this chart is saved/exported."""
        dialog = QDialog(self)
        dialog.setWindowTitle(f"Style — {self._title}")
        dialog.setMinimumWidth(340)
        dlg_layout = QVBoxLayout(dialog)

        panel = ChartStylePanel(chart_type=self._chart_type, style=self._style)
        panel.style_changed.connect(self._on_style_changed)
        dlg_layout.addWidget(panel)

        buttons = QDialogButtonBox(QDialogButtonBox.Close)
        buttons.rejected.connect(dialog.close)
        buttons.button(QDialogButtonBox.Close).clicked.connect(dialog.close)
        dlg_layout.addWidget(buttons)

        dialog.exec()

    def _on_style_changed(self, style: dict) -> None:
        """Live-apply a style change: re-derive from the ORIGINAL figure
        (self._base_fig), never from self._fig, so toggling a control on
        then off always gives a clean result instead of compounding on
        top of whatever the previous toggle left behind."""
        self._style = style
        self._meta["display_options"] = style
        styled_fig = apply_chart_style(self._base_fig, style, self._chart_type)
        self._fig = styled_fig
        self.plot_view.set_figure(styled_fig)
        self.style_changed.emit(self.uid, style)

    def current_meta(self) -> dict:
        """Return this card's metadata, including any style settings --
        callers persisting charts (session save, dashboard) should pull
        this instead of a stale meta dict captured before styling."""
        return dict(self._meta)